"""GuardIA-Sim: simulated Genesys processes for the test account (T3, Fase C, D18).

Test-only. It deploys the three orchestrators rebuilt from the sanitized
histories (infra/sim/definitions, generated by scripts/build_sim_definitions.py)
with their real names, `guardia:*` tags, and crons, plus `SIMNOAUTO`, the same
orchestrator tagged `escalate-only`. GuardIA cannot tell them apart from real
processes: it discovers them by tag, sees real executions and histories, and
its redrive acts on them for real. Only the work inside the steps is fake: one
stub Lambda that succeeds or fails as the SimScenarios table says.

`scripts/sim.py` drives the scenarios. The stack refuses any environment
whose configuration does not allow the simulator (production).
"""

from aws_cdk import CfnOutput, Duration, RemovalPolicy, Stack, Tags
from aws_cdk import aws_dynamodb as dynamodb
from aws_cdk import aws_events as events
from aws_cdk import aws_events_targets as targets
from aws_cdk import aws_iam as iam
from aws_cdk import aws_secretsmanager as secretsmanager
from aws_cdk import aws_sns as sns
from aws_cdk import aws_stepfunctions as sfn
from constructs import Construct

from components.function import SIM_LAMBDAS, GuardiaFunction
from config import EnvironmentConfig
from sim.processes import SCHEDULED_INPUT, sim_processes

STUB_MEMORY_MB = 128  # small on purpose: the oom scenario fills it


class SimNotAllowedError(ValueError):
    pass


class SimStack(Stack):
    def __init__(
        self,
        scope: Construct,
        construct_id: str,
        *,
        config: EnvironmentConfig,
        teams_alerts_secret: secretsmanager.ISecret,
        **kwargs,
    ) -> None:
        if not config.deploy_sim:
            raise SimNotAllowedError(
                f"GuardIA-Sim is test-only and is never deployed with env={config.name}"
            )
        super().__init__(scope, construct_id, **kwargs)
        Tags.of(self).add("guardia:simulated", "true")

        self.scenarios = dynamodb.Table(
            self,
            "SimScenarios",
            partition_key=dynamodb.Attribute(name="org", type=dynamodb.AttributeType.STRING),
            billing_mode=dynamodb.BillingMode.PAY_PER_REQUEST,
            time_to_live_attribute="expires_at",
            removal_policy=RemovalPolicy.DESTROY,
        )
        self.stub = GuardiaFunction(
            self,
            "StubTask",
            name="stub_task",
            code_root=SIM_LAMBDAS,
            layer=None,
            environment={"SCENARIOS_TABLE": self.scenarios.table_name},
            memory_size=STUB_MEMORY_MB,
            timeout_seconds=60,
            description="GuardIA-Sim: stand-in for every step of the simulated processes",
        )
        self.scenarios.grant(self.stub.function, "dynamodb:GetItem", "dynamodb:UpdateItem")
        self.alerts = sns.Topic(self, "Alerts", display_name="GuardIA-Sim process alerts")

        self.state_machines: dict[str, sfn.StateMachine] = {}
        self.rule_roles: dict[str, iam.Role] = {}
        for process in sim_processes():
            self._process(process)

        CfnOutput(self, "ScenariosTableName", value=self.scenarios.table_name)
        self._janitor(teams_alerts_secret)

    def _process(self, process) -> None:
        org = process.org
        machine = sfn.StateMachine(
            self,
            f"{org}StateMachine",
            state_machine_name=process.name,
            definition_body=sfn.DefinitionBody.from_file(str(process.definition_file)),
            definition_substitutions={
                "StubFunctionArn": self.stub.function.function_arn,
                "AlertsTopicArn": self.alerts.topic_arn,
            },
            removal_policy=RemovalPolicy.DESTROY,
        )
        self.stub.function.grant_invoke(machine)
        self.alerts.grant_publish(machine)
        for key, value in process.tags.items():
            Tags.of(machine).add(key, value)

        # Its own role, so `sim.py missed` can deny one process at a time.
        role = iam.Role(
            self, f"{org}RuleRole", assumed_by=iam.ServicePrincipal("events.amazonaws.com")
        )
        events.Rule(
            self,
            f"{org}Schedule",
            description=f"GuardIA-Sim: launches {process.name}",
            schedule=events.Schedule.expression(process.schedule),
            targets=[
                targets.SfnStateMachine(
                    machine, input=events.RuleTargetInput.from_object(SCHEDULED_INPUT), role=role
                )
            ],
        )
        self.state_machines[org] = machine
        self.rule_roles[org] = role
        CfnOutput(self, f"{org}StateMachineArn", value=machine.state_machine_arn)
        CfnOutput(self, f"{org}RuleRoleName", value=role.role_name)

    def _janitor(self, teams_alerts_secret: secretsmanager.ISecret) -> None:
        janitor = GuardiaFunction(
            self,
            "Janitor",
            name="janitor",
            code_root=SIM_LAMBDAS,
            layer=None,
            environment={"SCENARIOS_TABLE": self.scenarios.table_name},
            timeout_seconds=60,
            description="GuardIA-Sim: undoes expired missed and teams-down scenarios",
        ).function
        self.scenarios.grant(janitor, "dynamodb:Scan", "dynamodb:DeleteItem")
        janitor.add_to_role_policy(
            iam.PolicyStatement(
                sid="RestoreRuleRoles",
                actions=["iam:DeleteRolePolicy"],
                resources=[role.role_arn for role in self.rule_roles.values()],
            )
        )
        janitor.add_to_role_policy(
            iam.PolicyStatement(
                sid="RestoreTeamsSecret",
                actions=[
                    "secretsmanager:DescribeSecret",
                    "secretsmanager:UpdateSecretVersionStage",
                ],
                resources=[teams_alerts_secret.secret_arn],
            )
        )
        events.Rule(
            self,
            "JanitorSchedule",
            description="GuardIA-Sim: restore expired scenarios",
            schedule=events.Schedule.rate(Duration.minutes(5)),
            targets=[targets.LambdaFunction(janitor)],
        )
